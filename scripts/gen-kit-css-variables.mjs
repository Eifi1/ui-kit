#!/usr/bin/env node
/**
 * Generate src/testing/css-variables.generated.ts: the custom properties the kit
 * publishes (from tokens.css) and Tailwind's own theme variables (from the
 * `tailwindcss/theme.css` the kit builds with), for `@eifi1/ui-kit/testing`'s
 * `undeclaredCssVariables` (docs/colour-roles-harmonization.md §8.3).
 *
 * The guard is browser code and reads no files, so the lists travel inside the package,
 * baked from the installed versions — an app never searches `node_modules` for them.
 *
 * The rule is the guard's own `declaredCustomProperties`: every `--name:` in any block,
 * comments skipped, EXCEPT a name declared only inside `@theme inline` (Tailwind emits no
 * variable for it). `--app-nav-h` is left out on purpose: AppShell sets it only while it
 * is mounted. `src/__tests__/token-vars-declared.test.ts` re-derives both lists with the
 * TypeScript implementation and fails, naming this script, when this file is stale.
 *
 * Usage:
 *   node scripts/gen-kit-css-variables.mjs           rewrite the generated file
 *   node scripts/gen-kit-css-variables.mjs --check    exit 1 if it is stale
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { join, resolve } from "node:path";

const ROOT = resolve(import.meta.dirname, "..");
const OUT = join(ROOT, "src/testing/css-variables.generated.ts");
const require = createRequire(import.meta.url);
const TAILWIND_THEME = require.resolve("tailwindcss/theme.css", { paths: [ROOT] });
const TAILWIND_VERSION = JSON.parse(readFileSync(require.resolve("tailwindcss/package.json", { paths: [ROOT] }), "utf8")).version;

/** Mirrors `declaredCustomProperties` in src/testing/css-variables.ts. */
function declared(css) {
  const blank = (m) => m.replace(/[^\n]/g, " ");
  let code = css.replace(/\/\*[\s\S]*?\*\//g, blank);
  for (const m of code.matchAll(/@theme\b[^{;]*\binline\b[^{;]*\{/g)) {
    let depth = 0;
    let end = m.index + m[0].length - 1;
    for (; end < code.length; end++) {
      if (code[end] === "{") depth++;
      else if (code[end] === "}" && --depth === 0) break;
    }
    code = code.slice(0, m.index) + blank(code.slice(m.index, end + 1)) + code.slice(end + 1);
  }
  return new Set([...code.matchAll(/(--[a-zA-Z0-9_-]+)\s*:/g)].map((m) => m[1]));
}

const kit = [...declared(readFileSync(join(ROOT, "tokens.css"), "utf8"))].filter((n) => n !== "--app-nav-h").sort();
const tailwind = [...declared(readFileSync(TAILWIND_THEME, "utf8"))].sort();

/** Wrapped at ~100 columns, so a diff of the file shows which names moved. */
function wrap(names) {
  const lines = [];
  let line = "";
  for (const n of names) {
    if (line && line.length + n.length + 1 > 96) {
      lines.push(line);
      line = n;
    } else line = line ? `${line} ${n}` : n;
  }
  if (line) lines.push(line);
  return lines.map((l, i) => `  ${JSON.stringify(i < lines.length - 1 ? `${l} ` : l)}`).join(" +\n");
}

const text = `// GENERATED by scripts/gen-kit-css-variables.mjs — do not edit by hand. Re-run it after
// changing tokens.css or upgrading Tailwind; src/__tests__/token-vars-declared.test.ts
// fails while this is stale.

/** Every custom property tokens.css declares, \`@theme inline\` names and \`--app-nav-h\`
 *  left out (${kit.length} names). */
export const KIT_NAMES =
${wrap(kit)};

/** The theme variables of Tailwind ${TAILWIND_VERSION}'s \`theme.css\` (${tailwind.length} names). */
export const TAILWIND_THEME_NAMES =
${wrap(tailwind)};
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(OUT, "utf8");
  } catch {
    /* missing is stale */
  }
  if (current !== text) {
    console.error("✖ src/testing/css-variables.generated.ts is stale — run node scripts/gen-kit-css-variables.mjs");
    process.exit(1);
  }
  console.log("✓ src/testing/css-variables.generated.ts is current");
} else {
  writeFileSync(OUT, text);
  console.log(`✓ wrote ${kit.length} kit and ${tailwind.length} Tailwind names`);
}
