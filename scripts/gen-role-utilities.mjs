#!/usr/bin/env node
/**
 * Generate src/eslint/role-utilities.generated.ts: per property, the tokens that have a role
 * utility and its name, re-rendered from tokens.css's `@theme inline` block (round 0.35 R5,
 * Kurvenschmiede's Q6).
 *
 * Two readers, one table: `@eifi1/ui-kit/eslint`'s `role-utilities` rule, which an app's
 * ESLint loads in plain Node and so cannot read a stylesheet, and `npm run check:tokens`,
 * which fails while this file is stale. The parser is src/eslint/role-utilities.ts's, imported
 * from source (Node strips its types), so the check, this script and the README's table
 * (scripts/gen-styling-inventory.mjs, since 0.37) cannot read the block two ways.
 *
 * Usage:
 *   node scripts/gen-role-utilities.mjs           rewrite the generated file
 *   node scripts/gen-role-utilities.mjs --check    exit 1 if it is stale
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { roleUtilitiesFromCss } from "../src/eslint/role-utilities.ts";

const ROOT = resolve(import.meta.dirname, "..");
const OUT = join(ROOT, "src/eslint/role-utilities.generated.ts");

const table = roleUtilitiesFromCss(readFileSync(join(ROOT, "tokens.css"), "utf8"));
if (!table) {
  console.error("✖ tokens.css has no @theme inline block — the role utilities are gone, or this parser is");
  process.exit(1);
}

const q = JSON.stringify;
const body = Object.entries(table)
  .map(([prop, tokens]) => {
    const rows = Object.entries(tokens).map(([token, names]) => `    ${q(token)}: [${names.map(q).join(", ")}],`);
    return `  ${q(prop)}: {${rows.length ? `\n${rows.join("\n")}\n  ` : ""}},`;
  })
  .join("\n");

const out = `// GENERATED by scripts/gen-role-utilities.mjs from tokens.css's \`@theme inline\` block — do
// not edit. \`npm run check:tokens\` fails while it is stale; re-run the script.
//
// Per property, each token that has a role utility → the utility's name after the
// property's prefix (\`border\`: \`--border\` → \`subtle\`, i.e. \`border-subtle\`). Read by
// \`@eifi1/ui-kit/eslint\` and scripts/check-token-discipline.mjs (round 0.35 R5).
import type { RoleUtilityTable } from "./role-utilities";

export const ROLE_UTILITIES: RoleUtilityTable = {
${body}
};
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(OUT, "utf8");
  } catch {
    // missing counts as stale
  }
  if (current !== out) {
    console.error(`✖ ${OUT.slice(ROOT.length + 1)} is stale — run: node scripts/gen-role-utilities.mjs`);
    process.exit(1);
  }
  console.log(`✓ ${OUT.slice(ROOT.length + 1)} is current`);
} else {
  writeFileSync(OUT, out);
  const count = Object.values(table).reduce((n, tokens) => n + Object.keys(tokens).length, 0);
  console.log(`wrote ${OUT.slice(ROOT.length + 1)}: ${count} role utilities`);
}
